-- Postulaciones y admision al programa (CU26)
-- Al admitir se crean Usuario, Emprendedor y Emprendimiento en una sola transaccion (capa de aplicacion).
-- ============================================================
CREATE TABLE Postulaciones (
    Nombre VARCHAR(160) NOT NULL,
    Apellido VARCHAR(120) NOT NULL,
    Email VARCHAR(254) NOT NULL,
    Telefono VARCHAR(35),
    Documento_identidad VARCHAR(50),
    Nombre_emprendimiento VARCHAR(160) NOT NULL,
    Descripcion_emprendimiento TEXT,
    Sector VARCHAR(120),
    Fecha_postulacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Estado VARCHAR(40) NOT NULL DEFAULT 'pendiente',
    Fecha_decision TIMESTAMPTZ,
    Observaciones_decision TEXT,
    PostulacionesID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Decidido_por_usuarioID BIGINT,
    EmprendedorID BIGINT,
    EmprendimientoID BIGINT,
    CONSTRAINT ck_postulaciones_estado CHECK (Estado IN ('pendiente', 'admitida', 'rechazada')),
    CONSTRAINT ck_postulaciones_decision CHECK (
        (Estado = 'pendiente' AND Fecha_decision IS NULL AND Decidido_por_usuarioID IS NULL)
        OR (Estado <> 'pendiente' AND Fecha_decision IS NOT NULL AND Decidido_por_usuarioID IS NOT NULL)
    ),
    CONSTRAINT ck_postulaciones_vinculos CHECK (
        (Estado = 'admitida' AND EmprendedorID IS NOT NULL AND EmprendimientoID IS NOT NULL)
        OR (Estado <> 'admitida' AND EmprendedorID IS NULL AND EmprendimientoID IS NULL)
    ),
    CONSTRAINT fk_postulaciones_decidido_por FOREIGN KEY (Decidido_por_usuarioID) REFERENCES Usuario (UsuarioID) ON DELETE RESTRICT,
    CONSTRAINT fk_postulaciones_emprendedorid FOREIGN KEY (EmprendedorID) REFERENCES Emprendedor (EmprendedorID) ON DELETE RESTRICT,
    CONSTRAINT fk_postulaciones_emprendimientoid FOREIGN KEY (EmprendimientoID) REFERENCES Emprendimiento (EmprendimientoID) ON DELETE RESTRICT,
    CONSTRAINT uq_postulaciones_emprendedorid UNIQUE (EmprendedorID),
    CONSTRAINT uq_postulaciones_emprendimientoid UNIQUE (EmprendimientoID)
);
